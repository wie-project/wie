//! Chained-block register-handoff regression tests (iced vs JIT).
//!
//! The DOOM Retro parser crash: a micro-stub trampoline inside a chain left a
//! partial `gpr_dirty_bits` mask, so the outermost `run_compiled` writeback
//! synced only the stub's registers back to the host regfile — dropping the
//! lea block's `r12` (and other chain-written GPRs). The next dispatched
//! block reloaded a stale `r12` and the crash-site `call 0x131b18` received
//! `rcx = 0`. `trampolines::mark_dirty` now forces a full writeback whenever
//! a stub runs inside a chain (`chain_depth > 0`).

use super::*;

/// Run `code` at [`SIMD_BASE`] through iced (stepping until `stop_rip`) and
/// the JIT (chained `step_one` loop until `stop_rip`), then return both
/// register files. Unlike [`super::simd_dual`], supports loops and calls.
fn chain_dual(
    code: &[u8],
    stop_rip: u64,
    setup: impl Fn(&mut RegFile) + Copy,
    setup_mem: impl Fn(&mut dyn CpuEngine) + Copy,
) -> (RegFile, RegFile) {
    crate::exec::iced_decode_cache_flush();
    let mut iced = IcedCpu::open_x86_64();
    iced.virtual_alloc(
        SIMD_BASE,
        0x2000,
        MEM_RESERVE | MEM_COMMIT,
        protect::PAGE_EXECUTE_READWRITE,
    )
    .expect("iced alloc");
    iced.mem_write(SIMD_BASE, code).expect("iced code");
    setup_mem(&mut iced);
    setup(iced.regs_mut());
    iced.write_rip(SIMD_BASE).expect("iced rip");
    for _ in 0..500 {
        let rip = iced.read_rip().expect("iced rip read");
        if rip >= stop_rip {
            break;
        }
        if iced.step_once().is_err() {
            break;
        }
    }

    let mut cpu = JitCpu::open_x86_64();
    cpu.virtual_alloc(
        SIMD_BASE,
        0x2000,
        MEM_RESERVE | MEM_COMMIT,
        protect::PAGE_EXECUTE_READWRITE,
    )
    .expect("jit alloc");
    cpu.mem_write(SIMD_BASE, code).expect("jit code");
    setup_mem(&mut cpu);
    setup(&mut cpu.thread.regs);
    cpu.write_rip(SIMD_BASE).expect("jit rip");
    for _ in 0..500 {
        let rip = cpu.read_rip().expect("jit rip read");
        if rip >= stop_rip {
            break;
        }
        // A step may end on the harness's ud2 terminator (iced fallback
        // error) — that is the intended stop, not a failure.
        let Ok((result, _retired)) = cpu.step_one() else {
            break;
        };
        if !matches!(result, StepResult::Continue) {
            break;
        }
    }

    (iced.regs().clone(), cpu.thread.regs.clone())
}

